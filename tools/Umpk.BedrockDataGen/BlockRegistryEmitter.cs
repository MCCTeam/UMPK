using System.Globalization;
using System.Text;
using System.Text.Json;
using Umpk.BedrockDataGen.Schema;

namespace Umpk.BedrockDataGen;

internal static class BlockRegistryEmitter
{
    internal const string FrozenSourcePath = "data/bedrock/2169/imported/blockStates.json";
    internal const string PaletteSource = "inherited-frozen-1.26.30-via-dataPaths";
    internal const string NetworkPaletteStatus = "unresolved-live";
    internal const int UnknownHash = -2;

    public static void Emit(string blockStatesJsonPath, string outputPath, string sourceSha256)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(blockStatesJsonPath);
        ArgumentException.ThrowIfNullOrWhiteSpace(outputPath);
        ArgumentException.ThrowIfNullOrWhiteSpace(sourceSha256);
        using JsonDocument states = JsonDocument.Parse(File.ReadAllBytes(blockStatesJsonPath));
        Emitter.WriteGenerated(outputPath, Build(states.RootElement, sourceSha256));
    }

    public static void EmitFromDataRoot(string dataRoot, string dataOutput)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(dataRoot);
        ArgumentException.ThrowIfNullOrWhiteSpace(dataOutput);
        string inputPath = Path.Combine(dataRoot, "2169", "imported", "blockStates.json");
        if (!File.Exists(inputPath))
            throw new SchemaException("The frozen blockStates.json input is missing.");
        Emit(inputPath, Path.Combine(dataOutput, "Bedrock2169BlockRegistry.g.cs"), SchemaHash.ComputeFile(inputPath));
    }

    internal static string Build(JsonElement states, string sourceSha256)
    {
        if (states.ValueKind != JsonValueKind.Array)
            throw new SchemaException("The pinned blockStates.json input must contain a JSON array.");
        int count = states.GetArrayLength();
        if (count == 0)
            throw new SchemaException("The pinned blockStates.json input must contain a nonempty state table.");
        int airIndex = -1;
        for (int index = 0; index < count; index++)
        {
            JsonElement entry = states[index];
            if (!entry.TryGetProperty("name", out JsonElement name) || name.ValueKind != JsonValueKind.String || string.IsNullOrWhiteSpace(name.GetString()))
                throw new SchemaException($"The block state at stable index {index} has no name.");
            if (name.GetString()!.Equals("air", StringComparison.Ordinal) && airIndex < 0)
                airIndex = index;
        }

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("// Generated from data/bedrock/2169/imported/blockStates.json. Do not edit directly.");
        source.AppendLine("// Stable indices below are positions in the frozen source table and do not represent session runtime identifiers.");
        source.AppendLine("// Palette entries retain their wire values until a negotiated identity table resolves them, so consumers must preserve unknown identifiers.");
        source.AppendLine();
        source.AppendLine("namespace Umpk.Data.Bedrock.Generated;");
        source.AppendLine();
        source.AppendLine("internal static class Bedrock2169BlockRegistry");
        source.AppendLine("{");
        source.Append("    internal const string SourcePath = ").Append(JsonSerializer.Serialize(FrozenSourcePath)).AppendLine(";");
        source.Append("    internal const string SourceSha256 = ").Append(JsonSerializer.Serialize(sourceSha256)).AppendLine(";");
        source.Append("    internal const int StableCount = ").Append(count.ToString(CultureInfo.InvariantCulture)).AppendLine(";");
        source.Append("    internal const string PaletteSource = ").Append(JsonSerializer.Serialize(PaletteSource)).AppendLine(";");
        source.Append("    internal const string NetworkPaletteStatus = ").Append(JsonSerializer.Serialize(NetworkPaletteStatus)).AppendLine(";");
        source.Append("    internal const int UnknownHash = ").Append(UnknownHash.ToString(CultureInfo.InvariantCulture)).AppendLine(";");
        source.Append("    internal const int AirStableIndex = ").Append(airIndex.ToString(CultureInfo.InvariantCulture)).AppendLine(";");
        source.AppendLine("}");
        return source.ToString();
    }
}
