using System.Globalization;
using System.Text;
using System.Text.Json;
using Umpk.BedrockDataGen.Schema;

namespace Umpk.BedrockDataGen;

internal static class SkinEmitter
{
    internal const string FrozenSourcePath = "data/bedrock/2169/imported/steve.json";

    public static void Emit(string steveJsonPath, string outputPath, string sourceSha256)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(steveJsonPath);
        ArgumentException.ThrowIfNullOrWhiteSpace(outputPath);
        ArgumentException.ThrowIfNullOrWhiteSpace(sourceSha256);
        using JsonDocument steve = JsonDocument.Parse(File.ReadAllBytes(steveJsonPath));
        Emitter.WriteGenerated(outputPath, Build(steve.RootElement, sourceSha256));
    }

    internal static string Build(JsonElement steve, string sourceSha256)
    {
        if (steve.ValueKind != JsonValueKind.Object)
            throw new SchemaException("The pinned steve.json input must contain a JSON object.");
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("// Generated from data/bedrock/2169/imported/steve.json. Do not edit directly.");
        source.AppendLine();
        source.AppendLine("namespace Umpk.Client.Bedrock.Authentication;");
        source.AppendLine();
        source.AppendLine("internal static class BedrockDefaultSkin");
        source.AppendLine("{");
        source.Append("    internal const string SourcePath = ").Append(Literal(FrozenSourcePath)).AppendLine(";");
        source.Append("    internal const string SourceSha256 = ").Append(Literal(sourceSha256)).AppendLine(";");
        source.AppendLine();
        source.AppendLine("    internal static BedrockClientSkinProfile Profile => new(");
        AppendSkinProfile(source, steve);
        source.AppendLine("}");
        return source.ToString();
    }

    private static void AppendSkinProfile(StringBuilder source, JsonElement steve)
    {
        source.Append("        ").Append(Literal(GetString(steve, "SkinId"))).AppendLine(",");
        source.Append("        ").Append(Literal(GetString(steve, "SkinData"))).AppendLine(",");
        source.Append("        ").Append(GetInt32(steve, "SkinImageWidth").ToString(CultureInfo.InvariantCulture)).AppendLine(",");
        source.Append("        ").Append(GetInt32(steve, "SkinImageHeight").ToString(CultureInfo.InvariantCulture)).AppendLine(",");
        source.Append("        ").Append(Literal(GetString(steve, "SkinResourcePatch"))).AppendLine(",");
        source.Append("        ").Append(Literal(GetString(steve, "SkinGeometryData"))).AppendLine(",");
        source.Append("        ").Append(Literal(GetString(steve, "SkinGeometryDataEngineVersion"))).AppendLine(",");
        source.Append("        ").Append(Literal(GetString(steve, "CapeData"))).AppendLine(",");
        source.Append("        ").Append(GetInt32(steve, "CapeImageWidth").ToString(CultureInfo.InvariantCulture)).AppendLine(",");
        source.Append("        ").Append(GetInt32(steve, "CapeImageHeight").ToString(CultureInfo.InvariantCulture)).AppendLine(",");
        source.Append("        ").Append(GetBool(steve, "CapeOnClassicSkin") ? "true" : "false").AppendLine(",");
        source.Append("        ").Append(GetBool(steve, "PersonaSkin") ? "true" : "false").AppendLine(",");
        source.Append("        ").Append(GetBool(steve, "PremiumSkin") ? "true" : "false").AppendLine(",");
        AppendAnimations(source, steve);
        source.Append("        ").Append(Literal(GetString(steve, "ArmSize"))).AppendLine(",");
        source.Append("        ").Append(Literal(GetString(steve, "CapeId"))).AppendLine(",");
        AppendPersonaPieces(source, steve);
        AppendPieceTintColors(source, steve);
        source.Append("        ").Append(Literal(GetString(steve, "SkinAnimationData"))).AppendLine(",");
        source.Append("        ").Append(Literal(GetString(steve, "SkinColor"))).AppendLine(");");
    }

    private static void AppendAnimations(StringBuilder source, JsonElement steve)
    {
        source.AppendLine("        [");
        int index = 0;
        foreach (JsonElement animation in EnumerateArray(steve, "AnimatedImageData"))
        {
            if (index > 0)
                source.AppendLine(",");
            source.AppendLine("            new BedrockSkinAnimationData");
            source.AppendLine("            {");
            source.Append("                AnimationExpression = ").Append(GetInt32(animation, "AnimationExpression").ToString(CultureInfo.InvariantCulture)).AppendLine(",");
            source.Append("                Frames = ").Append(GetInt32(animation, "Frames").ToString(CultureInfo.InvariantCulture)).AppendLine(",");
            source.Append("                Image = ").Append(Literal(GetString(animation, "Image"))).AppendLine(",");
            source.Append("                ImageHeight = ").Append(GetInt32(animation, "ImageHeight").ToString(CultureInfo.InvariantCulture)).AppendLine(",");
            source.Append("                ImageWidth = ").Append(GetInt32(animation, "ImageWidth").ToString(CultureInfo.InvariantCulture)).AppendLine(",");
            source.Append("                Type = ").Append(GetInt32(animation, "Type").ToString(CultureInfo.InvariantCulture)).AppendLine(",");
            source.Append("            }");
            index++;
        }

        source.AppendLine();
        source.AppendLine("        ],");
    }

    private static void AppendPersonaPieces(StringBuilder source, JsonElement steve)
    {
        source.AppendLine("        [");
        int index = 0;
        foreach (JsonElement piece in EnumerateArray(steve, "PersonaPieces"))
        {
            if (index > 0)
                source.AppendLine(",");
            source.AppendLine("            new BedrockPersonaPiece");
            source.AppendLine("            {");
            source.Append("                IsDefault = ").Append(GetBool(piece, "IsDefault") ? "true" : "false").AppendLine(",");
            source.Append("                PackId = ").Append(Literal(GetString(piece, "PackId"))).AppendLine(",");
            source.Append("                PieceId = ").Append(Literal(GetString(piece, "PieceId"))).AppendLine(",");
            source.Append("                PieceType = ").Append(Literal(GetString(piece, "PieceType"))).AppendLine(",");
            source.Append("                ProductId = ").Append(Literal(GetString(piece, "ProductId"))).AppendLine(",");
            source.Append("            }");
            index++;
        }

        source.AppendLine();
        source.AppendLine("        ],");
    }

    private static void AppendPieceTintColors(StringBuilder source, JsonElement steve)
    {
        source.AppendLine("        [");
        int index = 0;
        foreach (JsonElement tint in EnumerateArray(steve, "PieceTintColors"))
        {
            if (index > 0)
                source.AppendLine(",");
            source.AppendLine("            new BedrockPersonaPieceTintColor");
            source.AppendLine("            {");
            source.Append("                Colors = [");
            int colorIndex = 0;
            foreach (JsonElement color in EnumerateArray(tint, "Colors"))
            {
                if (colorIndex > 0)
                    source.Append(", ");
                source.Append(Literal(GetElementString(color, "Colors")));
                colorIndex++;
            }

            source.AppendLine("],");
            source.Append("                PieceType = ").Append(Literal(GetString(tint, "PieceType"))).AppendLine(",");
            source.Append("            }");
            index++;
        }

        source.AppendLine();
        source.AppendLine("        ],");
    }

    private static IEnumerable<JsonElement> EnumerateArray(JsonElement parent, string name)
    {
        if (!parent.TryGetProperty(name, out JsonElement element) || element.ValueKind != JsonValueKind.Array)
            throw new SchemaException($"The pinned skin field '{name}' is missing or is not an array.");
        foreach (JsonElement item in element.EnumerateArray())
            yield return item;
    }

    private static string GetString(JsonElement parent, string name)
    {
        if (!parent.TryGetProperty(name, out JsonElement element))
            throw new SchemaException($"The pinned skin field '{name}' is missing.");
        return GetElementString(element, name);
    }

    private static string GetElementString(JsonElement element, string name)
    {
        return element.ValueKind switch
        {
            JsonValueKind.String => element.GetString() ?? throw new SchemaException($"The pinned skin field '{name}' is null."),
            JsonValueKind.Number => element.GetRawText(),
            JsonValueKind.True => "True",
            JsonValueKind.False => "False",
            _ => throw new SchemaException($"The pinned skin field '{name}' has an unsupported JSON kind."),
        };
    }

    private static int GetInt32(JsonElement parent, string name)
    {
        if (!parent.TryGetProperty(name, out JsonElement element))
            throw new SchemaException($"The pinned skin field '{name}' is missing.");
        if (element.ValueKind == JsonValueKind.Number && element.TryGetInt32(out int number))
            return number;
        if (element.ValueKind == JsonValueKind.String && int.TryParse(element.GetString(), NumberStyles.Integer, CultureInfo.InvariantCulture, out int parsed))
            return parsed;
        throw new SchemaException($"The pinned skin field '{name}' is not an integer.");
    }

    private static bool GetBool(JsonElement parent, string name)
    {
        if (!parent.TryGetProperty(name, out JsonElement element))
            throw new SchemaException($"The pinned skin field '{name}' is missing.");
        if (element.ValueKind is JsonValueKind.True)
            return true;
        if (element.ValueKind is JsonValueKind.False)
            return false;
        if (element.ValueKind == JsonValueKind.String && bool.TryParse(element.GetString(), out bool parsed))
            return parsed;
        throw new SchemaException($"The pinned skin field '{name}' is not a boolean.");
    }

    private static string Literal(string value)
    {
        var escaped = new StringBuilder(value.Length + 2);
        escaped.Append('"');
        foreach (char character in value)
        {
            switch (character)
            {
                case '"': escaped.Append("\\\""); break;
                case '\\': escaped.Append("\\\\"); break;
                case '\n': escaped.Append("\\n"); break;
                case '\r': escaped.Append("\\r"); break;
                case '\t': escaped.Append("\\t"); break;
                default:
                    if (char.IsControl(character))
                        escaped.Append("\\u").Append(((int)character).ToString("x4", CultureInfo.InvariantCulture));
                    else
                        escaped.Append(character);
                    break;
            }
        }

        escaped.Append('"');
        return escaped.ToString();
    }
}
