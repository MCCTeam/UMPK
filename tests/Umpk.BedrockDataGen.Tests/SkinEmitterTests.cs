using System.Text.Json;
using Xunit;

namespace Umpk.BedrockDataGen.Tests;

public sealed class SkinEmitterTests
{
    [Fact]
    public void TwoEmitsAreByteIdentical()
    {
        string stevePath = WriteSteveJson(MinimalSteve());
        using var first = new TemporaryDirectory();
        using var second = new TemporaryDirectory();

        SkinEmitter.Emit(stevePath, Path.Combine(first.Path, "skin.g.cs"), "aaa");
        SkinEmitter.Emit(stevePath, Path.Combine(second.Path, "skin.g.cs"), "aaa");

        Assert.Equal(
            File.ReadAllBytes(Path.Combine(first.Path, "skin.g.cs")),
            File.ReadAllBytes(Path.Combine(second.Path, "skin.g.cs")));
    }

    [Fact]
    public void EmittedSourceCarriesFrozenPathAndHash()
    {
        string stevePath = WriteSteveJson(MinimalSteve());
        using var output = new TemporaryDirectory();
        string skinPath = Path.Combine(output.Path, "skin.g.cs");

        SkinEmitter.Emit(stevePath, skinPath, "00af");

        string generated = File.ReadAllText(skinPath);
        Assert.Contains("data/bedrock/2169/imported/steve.json", generated, StringComparison.Ordinal);
        Assert.Contains("\"00af\"", generated, StringComparison.Ordinal);
        Assert.Contains("// <auto-generated />", generated, StringComparison.Ordinal);
        Assert.Contains("content-sha256:", generated, StringComparison.Ordinal);
        Assert.DoesNotContain("data/bedrock/1.21.70/steve.json", generated, StringComparison.Ordinal);
    }

    [Fact]
    public void EmittedSourceMapsSkinFieldsWithCoercion()
    {
        string stevePath = WriteSteveJson("""
            {
              "SkinId": "persona-test-0",
              "SkinData": "QUJD",
              "SkinImageWidth": "32",
              "SkinImageHeight": 64,
              "SkinResourcePatch": "e30=",
              "SkinGeometryData": "e30=",
              "SkinGeometryDataEngineVersion": "MS4xNC4w",
              "CapeData": "",
              "CapeImageWidth": 0,
              "CapeImageHeight": "0",
              "CapeOnClassicSkin": "False",
              "PersonaSkin": true,
              "PremiumSkin": false,
              "AnimatedImageData": [
                { "AnimationExpression": 1, "Frames": 2, "Image": "QUJD", "ImageHeight": 64, "ImageWidth": 32, "Type": 1 }
              ],
              "ArmSize": "wide",
              "CapeId": "",
              "PersonaPieces": [
                { "IsDefault": true, "PackId": "pack", "PieceId": "piece", "PieceType": "persona_body", "ProductId": "" }
              ],
              "PieceTintColors": [
                { "Colors": ["#ff000000", "#0"], "PieceType": "persona_eyes" }
              ],
              "SkinAnimationData": "",
              "SkinColor": "#ff112233"
            }
            """);
        using var output = new TemporaryDirectory();
        string skinPath = Path.Combine(output.Path, "skin.g.cs");

        SkinEmitter.Emit(stevePath, skinPath, "bbb");

        string generated = File.ReadAllText(skinPath);
        Assert.Contains("\"persona-test-0\"", generated, StringComparison.Ordinal);
        Assert.Contains("32,", generated, StringComparison.Ordinal);
        Assert.Contains("64,", generated, StringComparison.Ordinal);
        Assert.Contains("AnimationExpression = 1", generated, StringComparison.Ordinal);
        Assert.Contains("PieceType = \"persona_body\"", generated, StringComparison.Ordinal);
        Assert.Contains("Colors = [\"#ff000000\", \"#0\"]", generated, StringComparison.Ordinal);
        Assert.Contains("\"#ff112233\"", generated, StringComparison.Ordinal);
    }

    [Fact]
    public void MissingSkinFieldFailsClearly()
    {
        string stevePath = WriteSteveJson("""{ "SkinId": "persona-test-0" }""");
        using var output = new TemporaryDirectory();

        Schema.SchemaException exception = Assert.Throws<Schema.SchemaException>(() =>
            SkinEmitter.Emit(stevePath, Path.Combine(output.Path, "skin.g.cs"), "ccc"));

        Assert.Contains("SkinData", exception.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void GenerateSkinWithoutOptionsFailsClearly()
    {
        using var output = new StringWriter();
        using var error = new StringWriter();

        int exitCode = BedrockDataGenCli.Run(["generate-skin"], output, error);

        Assert.Equal(2, exitCode);
        Assert.Contains("--data-root", error.ToString(), StringComparison.Ordinal);
    }

    private static string MinimalSteve() => """
        {
          "SkinId": "persona-test-0",
          "SkinData": "QUJD",
          "SkinImageWidth": 32,
          "SkinImageHeight": 32,
          "SkinResourcePatch": "e30=",
          "SkinGeometryData": "e30=",
          "SkinGeometryDataEngineVersion": "MS4xNC4w",
          "CapeData": "",
          "CapeImageWidth": 0,
          "CapeImageHeight": 0,
          "CapeOnClassicSkin": false,
          "PersonaSkin": true,
          "PremiumSkin": false,
          "AnimatedImageData": [],
          "ArmSize": "wide",
          "CapeId": "",
          "PersonaPieces": [],
          "PieceTintColors": [],
          "SkinAnimationData": "",
          "SkinColor": "#ff112233"
        }
        """;

    private static string WriteSteveJson(string json)
    {
        using JsonDocument parsed = JsonDocument.Parse(json);
        string path = Path.Combine(Path.GetTempPath(), $"umpk-steve-{Guid.NewGuid():N}.json");
        File.WriteAllText(path, json);
        return path;
    }
}
