using System.Globalization;
using System.Text;
using System.Text.Json;
using Umpk.BedrockDataGen.Schema;

namespace Umpk.BedrockDataGen;

internal static class Emitter
{
    public static void Emit(
        GeneratedProfile profile,
        IReadOnlyList<RequiredPacket> packets,
        string protocolOutput,
        string dataOutput)
    {
        ArgumentNullException.ThrowIfNull(profile);
        ArgumentNullException.ThrowIfNull(packets);
        ArgumentException.ThrowIfNullOrWhiteSpace(protocolOutput);
        ArgumentException.ThrowIfNullOrWhiteSpace(dataOutput);
        foreach (RequiredPacket packet in packets)
            ConcreteCodecBindings.Validate(packet);
        Directory.CreateDirectory(protocolOutput);
        Directory.CreateDirectory(dataOutput);

        WriteGenerated(
            Path.Combine(protocolOutput, "Bedrock2169PacketCatalog.g.cs"),
            BuildPacketCatalog(packets));
        WriteGenerated(
            Path.Combine(protocolOutput, "Bedrock2169CodecRegistry.g.cs"),
            BuildCodecRegistry(packets));
        WriteGenerated(
            Path.Combine(dataOutput, "Bedrock2169DataProfile.g.cs"),
            BuildDataProfile(profile));
    }

    public static void EmitJoinTolerance(IReadOnlyList<JoinToleratedPacket> tolerances, string protocolOutput)
    {
        ArgumentNullException.ThrowIfNull(tolerances);
        ArgumentException.ThrowIfNullOrWhiteSpace(protocolOutput);
        Directory.CreateDirectory(protocolOutput);
        WriteGenerated(
            Path.Combine(protocolOutput, "Bedrock2169JoinTolerance.g.cs"),
            BuildJoinTolerance(tolerances));
    }

    private static string BuildJoinTolerance(IReadOnlyList<JoinToleratedPacket> tolerances)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine("using System.Collections.Immutable;");
        source.AppendLine();
        source.AppendLine("namespace Umpk.Protocol.Bedrock;");
        source.AppendLine();
        source.AppendLine("internal readonly record struct Bedrock2169ToleratedPacket(int PacketId, string Name);");
        source.AppendLine();
        source.AppendLine("internal static class Bedrock2169JoinTolerance");
        source.AppendLine("{");
        source.AppendLine("    internal static readonly ImmutableArray<Bedrock2169ToleratedPacket> Packets =");
        source.AppendLine("    [");
        foreach (JoinToleratedPacket packet in tolerances.OrderBy(static packet => packet.Id))
            source.Append("        new(").Append(packet.Id.ToString(CultureInfo.InvariantCulture)).Append(", ").Append(Literal(packet.Name)).AppendLine("),");
        source.AppendLine("    ];");
        source.AppendLine();
        source.AppendLine("    internal static bool IsTolerated(int packetId) => packetId switch");
        source.AppendLine("    {");
        foreach (JoinToleratedPacket packet in tolerances.OrderBy(static packet => packet.Id))
            source.Append("        ").Append(packet.Id.ToString(CultureInfo.InvariantCulture)).AppendLine(" => true,");
        source.AppendLine("        _ => false,");
        source.AppendLine("    };");
        source.AppendLine();
        source.AppendLine("    internal static string Name(int packetId) => packetId switch");
        source.AppendLine("    {");
        foreach (JoinToleratedPacket packet in tolerances.OrderBy(static packet => packet.Id))
            source.Append("        ").Append(packet.Id.ToString(CultureInfo.InvariantCulture)).Append(" => ").Append(Literal(packet.Name)).AppendLine(",");
        source.AppendLine("        _ => $\"packet_{packetId}\",");
        source.AppendLine("    };");
        source.AppendLine("}");
        return source.ToString();
    }

    private static string BuildPacketCatalog(IReadOnlyList<RequiredPacket> packets)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine("using System.Collections.Immutable;");
        source.AppendLine();
        source.AppendLine("namespace Umpk.Protocol.Bedrock.Generated;");
        source.AppendLine();
        source.AppendLine("internal readonly record struct GeneratedBedrockPacketDescriptor(int Id, string Name, string Direction, string Support, string Evidence, string LayoutHash, bool SchemaVerified, string Owner, string Binding, string? Codec, string Capability, string RegistryGeneration, string? BlockReason);");
        source.AppendLine();
        source.AppendLine("internal static class Bedrock2169PacketCatalog");
        source.AppendLine("{");
        source.AppendLine("    internal static readonly ImmutableArray<GeneratedBedrockPacketDescriptor> Packets =");
        source.AppendLine("    [");
        foreach (RequiredPacket packet in packets.OrderBy(static packet => packet.Id))
        {
            source.Append("        new(")
                .Append(packet.Id.ToString(CultureInfo.InvariantCulture)).Append(", ")
                .Append(Literal(packet.Name)).Append(", ")
                .Append(Literal(packet.Direction)).Append(", ")
                .Append(Literal(packet.Support)).Append(", ")
                .Append(Literal(packet.Evidence)).Append(", ")
                .Append(Literal(packet.LayoutHash)).Append(", ")
                .Append(packet.SchemaVerified ? "true" : "false").Append(", ")
                .Append(Literal(packet.Owner)).Append(", ")
                .Append(Literal(packet.Binding)).Append(", ")
                .Append(NullableLiteral(packet.Codec)).Append(", ")
                .Append(Literal(packet.Capability)).Append(", ")
                .Append(Literal(packet.RegistryGeneration)).Append(", ")
                .Append(NullableLiteral(packet.BlockReason))
                .AppendLine("),");
        }
        source.AppendLine("    ];");
        source.AppendLine();
        source.AppendLine("    internal static bool TryGet(int id, out GeneratedBedrockPacketDescriptor descriptor)");
        source.AppendLine("    {");
        source.AppendLine("        descriptor = id switch");
        source.AppendLine("        {");
        int packetIndex = 0;
        foreach (RequiredPacket packet in packets.OrderBy(static packet => packet.Id))
        {
            source.Append("            ")
                .Append(packet.Id.ToString(CultureInfo.InvariantCulture))
                .Append(" => Packets[")
                .Append(packetIndex.ToString(CultureInfo.InvariantCulture))
                .AppendLine("],");
            packetIndex++;
        }
        source.AppendLine("            _ => default,");
        source.AppendLine("        };");
        source.AppendLine("        return descriptor.Name is not null;");
        source.AppendLine("    }");
        source.AppendLine("}");
        return source.ToString();
    }

    private static string BuildCodecRegistry(IReadOnlyList<RequiredPacket> packets)
    {
        RequiredPacket[] registered = packets
            .Where(static packet => packet.Binding is "verified" or "blocked")
            .OrderBy(static packet => packet.Id)
            .ToArray();
        var concrete = registered
            .Where(static packet => packet.Binding.Equals("verified", StringComparison.Ordinal))
            .ToDictionary(static packet => packet.Id, ConcreteCodecBindings.Require);

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine("using System.Collections.Immutable;");
        source.AppendLine();
        source.AppendLine("namespace Umpk.Protocol.Bedrock;");
        source.AppendLine();
        source.AppendLine("internal delegate object Bedrock2169PacketDecoder(ReadOnlySpan<byte> payload, BedrockSessionCodecContext context);");
        source.AppendLine();
        source.AppendLine("internal enum BedrockRegistryGeneration");
        source.AppendLine("{");
        source.AppendLine("    None = 0,");
        source.AppendLine("    ItemRegistry = 1,");
        source.AppendLine("    EntityIdentifiers = 2,");
        source.AppendLine("}");
        source.AppendLine();
        source.AppendLine("internal readonly record struct Bedrock2169CodecBinding(int PacketId, string Name, string DeclaredDirection, BedrockPacketDirection? ExpectedDirection, string Capability, string Support, BedrockRegistryGeneration RegistryGeneration, Bedrock2169PacketDecoder? Decoder, string? BlockReason);");
        source.AppendLine();
        source.AppendLine("internal static class Bedrock2169CodecRegistry");
        source.AppendLine("{");
        source.AppendLine("    internal static readonly ImmutableArray<Bedrock2169CodecBinding> Bindings =");
        source.AppendLine("    [");
        foreach (RequiredPacket packet in registered)
        {
            ConcreteCodecBinding? binding = concrete.GetValueOrDefault(packet.Id);
            source.Append("        new(")
                .Append(packet.Id.ToString(CultureInfo.InvariantCulture)).Append(", ")
                .Append(Literal(packet.Name)).Append(", ")
                .Append(Literal(packet.Direction)).Append(", ")
                .Append(ExpectedDirection(packet.Direction)).Append(", ")
                .Append(Literal(packet.Capability)).Append(", ")
                .Append(Literal(packet.Support)).Append(", ")
                .Append(RegistryGeneration(packet.RegistryGeneration)).Append(", ")
                .Append(binding is null ? "null" : binding.AdapterName).Append(", ")
                .Append(NullableLiteral(packet.BlockReason))
                .AppendLine("),");
        }
        source.AppendLine("    ];");
        source.AppendLine();
        source.AppendLine("    internal static bool TryGet(int packetId, out Bedrock2169CodecBinding binding)");
        source.AppendLine("    {");
        source.AppendLine("        binding = packetId switch");
        source.AppendLine("        {");
        for (int index = 0; index < registered.Length; index++)
        {
            source.Append("            ")
                .Append(registered[index].Id.ToString(CultureInfo.InvariantCulture))
                .Append(" => Bindings[")
                .Append(index.ToString(CultureInfo.InvariantCulture))
                .AppendLine("],");
        }
        source.AppendLine("            _ => default,");
        source.AppendLine("        };");
        source.AppendLine("        return binding.Name is not null;");
        source.AppendLine("    }");
        source.AppendLine();
        source.AppendLine("    internal static object Decode(BedrockBatchMember member, BedrockSessionCodecContext context) => Decode(member, context, out _);");
        source.AppendLine();
        source.AppendLine("    internal static object Decode(BedrockBatchMember member, BedrockSessionCodecContext context, out Bedrock2169CodecBinding binding)");
        source.AppendLine("    {");
        source.AppendLine("        ArgumentNullException.ThrowIfNull(member);");
        source.AppendLine("        ArgumentNullException.ThrowIfNull(context);");
        source.AppendLine("        if (!TryGet(member.Header.PacketId, out binding))");
        source.AppendLine("            throw new BedrockCodecException($\"Packet {member.Header.PacketId} has no bound 2169 codec.\");");
        source.AppendLine("        if (binding.Decoder is null)");
        source.AppendLine("            throw new BedrockCodecException(binding.BlockReason ?? $\"Packet {member.Header.PacketId} has no bound 2169 codec.\");");
        source.AppendLine("        if (binding.ExpectedDirection is BedrockPacketDirection expected && context.Routing.Direction != expected)");
        source.AppendLine("            throw new BedrockCodecException($\"Packet {member.Header.PacketId} is {expected} but was dispatched as {context.Routing.Direction}.\");");
        source.AppendLine("        return binding.Decoder(member.Payload, context);");
        source.AppendLine("    }");

        foreach (ConcreteCodecBinding binding in concrete.Values.OrderBy(static binding => binding.PacketId))
        {
            source.AppendLine();
            source.Append("    private static object ").Append(binding.AdapterName).Append("(ReadOnlySpan<byte> payload, BedrockSessionCodecContext context) => ")
                .Append(binding.DecodeInvocation).AppendLine(";");
        }
        source.AppendLine("}");
        return source.ToString();
    }

    private static string BuildDataProfile(GeneratedProfile profile)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("using System.Collections.Immutable;");
        source.AppendLine();
        source.AppendLine("namespace Umpk.Data.Bedrock.Generated;");
        source.AppendLine();
        source.AppendLine("internal readonly record struct GeneratedBedrockInput(string Key, string SourcePath, string Sha256, string Role);");
        source.AppendLine();
        source.AppendLine("internal static class Bedrock2169DataProfile");
        source.AppendLine("{");
        source.Append("    internal const string Id = ").Append(Literal(profile.Id)).AppendLine(";");
        source.Append("    internal const string Release = ").Append(Literal(profile.Release)).AppendLine(";");
        source.Append("    internal const int ProtocolVersion = ").Append(profile.ProtocolVersion.ToString(CultureInfo.InvariantCulture)).AppendLine(";");
        source.Append("    internal const string Dialect = ").Append(Literal(profile.Dialect)).AppendLine(";");
        source.Append("    internal const string DataProfile = ").Append(Literal(profile.DataProfile)).AppendLine(";");
        source.Append("    internal const string BehaviorProfile = ").Append(Literal(profile.BehaviorProfile)).AppendLine(";");
        source.Append("    internal const int PredictionFlagLogicalBits = ").Append(profile.PredictionFlagLogicalBits.ToString(CultureInfo.InvariantCulture)).AppendLine(";");
        source.Append("    internal const int PredictionFlagEncodedBytes = ").Append(profile.PredictionFlagEncodedBytes.ToString(CultureInfo.InvariantCulture)).AppendLine(";");
        source.Append("    internal const int PredictionFlagMaxBytes = ").Append(profile.PredictionFlagMaxBytes.ToString(CultureInfo.InvariantCulture)).AppendLine(";");
        source.Append("    internal const string ImportManifestSha256 = ").Append(Literal(profile.ImportManifestSha256)).AppendLine(";");
        source.Append("    internal const string SchemaSha256 = ").Append(Literal(profile.SchemaSha256)).AppendLine(";");
        source.AppendLine();
        source.AppendLine("    internal static readonly ImmutableArray<GeneratedBedrockInput> Inputs =");
        source.AppendLine("    [");
        foreach (ImportedInput input in profile.Inputs.OrderBy(static input => input.Key, StringComparer.Ordinal))
        {
            source.Append("        new(")
                .Append(Literal(input.Key)).Append(", ")
                .Append(Literal(input.SourcePath)).Append(", ")
                .Append(Literal(input.Sha256)).Append(", ")
                .Append(Literal(input.Role)).AppendLine("),");
        }
        source.AppendLine("    ];");
        source.AppendLine();
        source.AppendLine("    internal static readonly ImmutableArray<string> Evidence =");
        source.AppendLine("    [");
        foreach (ProfileEvidence evidence in profile.Evidence.OrderBy(static evidence => evidence.Id, StringComparer.Ordinal))
            source.Append("        ").Append(Literal($"{evidence.Id}:{evidence.Status}:{evidence.Disposition}")).AppendLine(",");
        source.AppendLine("    ];");
        source.AppendLine("}");
        return source.ToString();
    }

    internal static void WriteGenerated(string path, string body)
    {
        string normalized = body.Replace("\r\n", "\n", StringComparison.Ordinal).TrimEnd('\n') + "\n";
        string hash = SchemaHash.Compute(Encoding.UTF8.GetBytes(normalized));
        File.WriteAllText(path, $"{normalized}// content-sha256: {hash}\n", new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
    }

    private static string ExpectedDirection(string direction) => direction switch
    {
        "clientbound" => "BedrockPacketDirection.Clientbound",
        "serverbound" => "BedrockPacketDirection.Serverbound",
        _ => "null",
    };

    private static string RegistryGeneration(string generation) => generation switch
    {
        "none" => "BedrockRegistryGeneration.None",
        "item-registry" => "BedrockRegistryGeneration.ItemRegistry",
        "entity-identifiers" => "BedrockRegistryGeneration.EntityIdentifiers",
        _ => throw new SchemaException($"Unsupported registry generation '{generation}'."),
    };

    private static string NullableLiteral(string? value) => value is null ? "null" : Literal(value);

    private static string Literal(string value) => JsonSerializer.Serialize(value);
}
